/**
 * The music folder as the HTTP layer sees it. Read-only parts are required;
 * the actions are optional (a fixed folder offers none).
 */
export interface LibraryAccess {
  status(): LibraryStatus;
  /** Read access for playback; null before a folder is chosen. */
  reader(): Pick<LibraryReader, 'audioFile' | 'readAudioRange'> | null;
  subscribe?(listener: (status: LibraryStatus) => void): () => void;
  setRoot?(path: string): Promise<LibraryStatus>;
  rescan?(full: boolean): LibraryStatus;
  setWatching?(on: boolean): LibraryStatus;
}

/** A folder that cannot be changed from the app (tests; SONIC_LIBRARY_ROOT). */
export function fixedLibrary(
  root: string | null,
  reader: Pick<LibraryReader, 'audioFile' | 'readAudioRange'> | null = null,
): LibraryAccess {
  return {
    status: () => ({
      root,
      source: root === null ? null : 'env',
      watching: false,
      state: root === null ? 'unconfigured' : 'idle',
      progress: null,
      error: null,
    }),
    reader: () => reader,
  };
}

export interface AppDeps {
  readonly queries: CatalogQueries;
  /** Builds the library health report (M5). */
  readonly healthReport: () => HealthReport;
  /** `<cacheDir>/artwork`: the only directory files are served from. */
  readonly artworkDir: string;
  /** The music folder: status, read access for playback, and (optionally) actions. */
  readonly library: LibraryAccess;
  /** Secret for write requests (random per start unless given, e.g. in tests). */
  readonly sessionToken?: string;
  /** Where the folder picker starts. */
  readonly homeDir?: string;
  /** Converts formats browsers cannot play; without it they are not playable. */
  readonly transcoder?: Transcoder;
  /** How often the events stream checks for a finished scan. */
  readonly eventsPollMs?: number;
  /** Built web app to serve at `/` (production); omitted in development. */
  readonly webDist?: string;
  readonly allowedHostnames?: ReadonlySet<string>;
}

/** Cache file names are generated by us: sha256 + raster extension. */
const ARTWORK_FILE = /^[0-9a-f]{64}\.(jpg|png|gif|webp|tif)$/;

class NotFound extends Error {}

export function createApp(deps: AppDeps): express.Express {
  const { queries } = deps;
  const artwork = createArtworkRenderer(deps.artworkDir);
  const app = express();
  app.disable('x-powered-by');
  app.set('etag', 'strong');

  app.use(hostGuard(deps.allowedHostnames ?? LOOPBACK_HOSTNAMES));
  app.use(securityHeaders);
  app.use(readOnlyMethods);
  const sessionToken = deps.sessionToken ?? randomBytes(32).toString('hex');
  app.use(writeGuard(sessionToken, deps.allowedHostnames ?? LOOPBACK_HOSTNAMES));

  const api = express.Router();
  api.use(apiContentSecurityPolicy);

  api.get('/health', (_req, res) => {
    const body: Health = {
      status: 'ok',
      library: {
        configured: deps.library.status().root !== null,
        available: isDirectory(deps.library.status().root),
      },
      transcoding: deps.transcoder !== undefined,
      lastScan: queries.lastScan(),
    };
    res.json(body);
  });

  api.get('/health-report', (_req, res) => {
    res.json(deps.healthReport());
  });

  api.get('/stats', (_req, res) => {
    res.json(queries.stats());
  });

  api.get('/facets', (_req, res) => {
    res.json(queries.facets());
  });

  api.get('/albums', (req, res) => {
    res.json(queries.listAlbums(parse(albumListQuery, req.query)));
  });

  api.get('/albums/:id', (req, res) => {
    res.json(found(queries.getAlbum(parse(idParams, req.params).id)));
  });

  // Playback. Files are addressed by catalog id only; the stored path is
  // re-checked inside the library root by the reader before any read.
  api.get('/files/:id/audio', async (req, res, next) => {
    const file = found(queries.getAudioFile(parse(idParams, req.params).id));
    const { start } = parse(audioQuery, req.query);
    const library = deps.library.reader();
    if (!library) throw new NotFound();
    let size: number;
    let absolute: string;
    try {
      ({ size, absolute } = await library.audioFile(file.relPath));
    } catch {
      throw new NotFound();
    }
    res.setHeader('Cache-Control', 'no-store');

    if (file.playback.mode === 'transcode') {
      if (!deps.transcoder) {
        const body: ApiError = {
          error: {
            code: 'UNAVAILABLE',
            message: `Playing ${file.codec ?? 'this format'} needs ffmpeg, which is not installed.`,
          },
        };
        res.status(503).json(body);
        return;
      }
      const stream = deps.transcoder.stream(absolute, start ?? 0, file.codec);
      if (stream === null) {
        res.status(503).json({ error: { code: 'BUSY', message: 'Too many conversions at once.' } });
        return;
      }
      res.type('audio/flac');
      res.setHeader('Accept-Ranges', 'none');
      res.on('close', () => stream.destroy());
      stream.pipe(res);
      return;
    }

    const range = parseRange(req.headers.range, size);
    if (range === 'invalid') {
      res.status(416).setHeader('Content-Range', `bytes */${size}`).end();
      return;
    }
    const { start: from, end: to } = range ?? { start: 0, end: size - 1 };
    res.status(range ? 206 : 200);
    res.type(file.playback.mime);
    res.setHeader('Accept-Ranges', 'bytes');
    res.setHeader('Content-Length', String(size === 0 ? 0 : to - from + 1));
    if (range) res.setHeader('Content-Range', `bytes ${from}-${to}/${size}`);
    if (req.method === 'HEAD' || size === 0) {
      res.end();
      return;
    }
    const stream = await library.readAudioRange(file.relPath, from, to);
    stream.on('error', (error) => (res.headersSent ? res.destroy(error) : next(error)));
    res.on('close', () => stream.destroy());
    stream.pipe(res);
  });

  // The app's own page reads this token and sends it with every change
  // request; other websites cannot read it (no CORS headers are sent).
  api.get('/session', (_req, res) => {
    res.setHeader('Cache-Control', 'no-store');
    res.json({ token: sessionToken });
  });

  api.get('/library', (_req, res) => {
    res.setHeader('Cache-Control', 'no-store');
    res.json(deps.library.status());
  });

  // Folder names for the music folder picker; no files, no recursion.
  api.get('/folders', (req, res) => {
    const { path: folder } = parse(folderQuery, req.query);
    res.json(listFolders(folder, deps.homeDir));
  });

  const body = express.json({ limit: '8kb' });

  api.put('/library', body, async (req, res) => {
    if (!deps.library.setRoot) throw new NotFound();
    const { path: folder } = parse(chooseFolderBody, req.body);
    res.json(await deps.library.setRoot(folder));
  });

  api.post('/library/scan', body, (req, res) => {
    if (!deps.library.rescan) throw new NotFound();
    const { full } = parse(rescanBody, req.body);
    res.json(deps.library.rescan(full));
  });

  api.put('/library/settings', body, (req, res) => {
    if (!deps.library.setWatching) throw new NotFound();
    const { watch } = parse(settingsBody, req.body);
    res.json(deps.library.setWatching(watch));
  });

  // Server-sent events: tells open pages when a scan has finished, so they
  // can refresh. It only reads the scan history; any scan (CLI or the
  // `start:watch` watcher) is noticed.
  api.get('/events', (req, res) => {
    res.writeHead(200, {
      'Content-Type': 'text/event-stream',
      'Cache-Control': 'no-store',
      Connection: 'keep-alive',
    });
    let last: string | null = null;
    let quietTicks = 0;
    const check = () => {
      const scan = queries.lastScan();
      const key = scan && scan.status !== 'running' ? `${scan.id}:${scan.finishedAt}` : null;
      if (last === null && scan === null) {
        // No scan yet (a new install): say so, so the first one is news.
        res.write('event: scan\ndata: null\n\n');
        last = 'none';
      } else if (scan && key !== null && key !== last) {
        res.write(`event: scan\ndata: ${JSON.stringify(scan)}\n\n`);
        last = key;
        quietTicks = 0;
      } else if (++quietTicks * (deps.eventsPollMs ?? 2000) >= 25_000) {
        res.write(': keep-alive\n\n');
        quietTicks = 0;
      }
    };
    check();
    const timer = setInterval(check, deps.eventsPollMs ?? 2000);
    // Library status (scanning progress, folder changes) as it happens.
    const sendStatus = (status: LibraryStatus) =>
      res.write(`event: library\ndata: ${JSON.stringify(status)}\n\n`);
    sendStatus(deps.library.status());
    const unsubscribe = deps.library.subscribe?.(sendStatus);
    req.on('close', () => {
      clearInterval(timer);
      unsubscribe?.();
    });
  });

  api.get('/statistics', (_req, res) => {
    res.json(queries.statistics());
  });

  api.get('/rip-logs/:id', (req, res) => {
    res.json(found(queries.getRipLog(parse(idParams, req.params).id)));
  });

  api.get('/tracks', (req, res) => {
    res.json(queries.listTracks(parse(trackListQuery, req.query)));
  });

  api.get('/artists', (req, res) => {
    res.json(queries.listArtists(parse(artistListQuery, req.query)));
  });

  api.get('/artists/:id', (req, res) => {
    res.json(found(queries.getArtist(parse(idParams, req.params).id)));
  });

  api.get('/search', (req, res) => {
    res.json(queries.search(parse(searchQuery, req.query).q));
  });

  api.get('/scans', (req, res) => {
    res.json(queries.listScans(parse(scanListQuery, req.query).limit));
  });

  api.get('/scans/:id', (req, res) => {
    res.json(found(queries.getScan(parse(idParams, req.params).id)));
  });

  api.get('/artwork/:id', async (req, res, next) => {
    const art = found(queries.getArtwork(parse(idParams, req.params).id));
    const { size } = parse(artworkQuery, req.query);
    // Defence in depth: the name comes from our own database, but it is still
    // checked before it gets anywhere near the filesystem.
    if (!ARTWORK_FILE.test(art.cacheFile)) throw new NotFound();
    let file: string;
    try {
      file = await artwork.render(art.cacheFile, size);
    } catch {
      // Missing from the cache, or not decodable: the UI shows a placeholder.
      throw new NotFound();
    }
    res.type('image/webp');
    // Content-addressed: the bytes behind an artwork URL never change.
    res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
    // Served relative to its directory: `send` refuses absolute paths that
    // pass through a dot-directory, and the cache lives under ~/.cache.
    res.sendFile(path.basename(file), { root: path.dirname(file) }, (error) => {
      if (error && !res.headersSent) next(new NotFound());
    });
  });

  api.use((_req, _res, next) => next(new NotFound()));
  app.use('/api', api);

  if (deps.webDist) {
    const webDist = deps.webDist;
    app.use(webContentSecurityPolicy);
    app.use(express.static(webDist, { index: false, dotfiles: 'deny', maxAge: '1h' }));
    // Client-side routes all render the app shell.
    app.get(/^\/(?!api\/).*/, (_req, res) => {
      res.sendFile('index.html', { root: webDist });
    });
  }

  app.use(errorHandler);
  return app;
}

function parse<T extends z.ZodType>(schema: T, input: unknown): z.infer<T> {
  return schema.parse(input);
}

function found<T>(value: T | null): T {
  if (value === null) throw new NotFound();
  return value;
}

function isDirectory(p: string | null): boolean {
  if (p === null) return false;
  try {
    return fs.statSync(p).isDirectory();
  } catch {
    return false;
  }
}

const errorHandler: ErrorRequestHandler = (error, _req: Request, res: Response, _next) => {
  let status = 500;
  let body: ApiError = { error: { code: 'INTERNAL', message: 'Internal error.' } };
  if (error instanceof ZodError) {
    status = 400;
    body = {
      error: {
        code: 'BAD_REQUEST',
        message: 'Invalid request.',
        issues: error.issues.map((i) => ({
          path: i.path.join('.') || '(query)',
          message: i.message,
        })),
      },
    };
  } else if (error instanceof ConfigError || error instanceof FolderError) {
    // Why a folder was refused: written for people ("not a directory", …).
    status = 400;
    body = { error: { code: 'INVALID_FOLDER', message: error.message } };
  } else if (error instanceof NotFound) {
    status = 404;
    body = { error: { code: 'NOT_FOUND', message: 'Not found.' } };
  } else {
    // Details stay in the server log; the client gets a generic message.
    console.error(error);
  }
  if (res.headersSent) return;
  res.status(status).json(body);
};
