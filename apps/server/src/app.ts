import fs from 'node:fs';
import path from 'node:path';
import type { CatalogQueries } from '@sonic-archive/catalog';
import {
  type ApiError,
  albumListQuery,
  artistListQuery,
  artworkQuery,
  type Health,
  type HealthReport,
  idParams,
  scanListQuery,
  searchQuery,
  trackListQuery,
} from '@sonic-archive/contracts';
import express, { type ErrorRequestHandler, type Request, type Response } from 'express';
import { ZodError, type z } from 'zod';
import { createArtworkRenderer } from './artwork.ts';
import {
  apiContentSecurityPolicy,
  hostGuard,
  LOOPBACK_HOSTNAMES,
  readOnlyMethods,
  securityHeaders,
  webContentSecurityPolicy,
} from './security.ts';

export interface AppDeps {
  readonly queries: CatalogQueries;
  /** Builds the library health report (M5). */
  readonly healthReport: () => HealthReport;
  /** `<cacheDir>/artwork`: the only directory files are served from. */
  readonly artworkDir: string;
  /** Canonical library root, or null when unconfigured. Only ever stat'ed. */
  readonly libraryRoot: string | null;
  /** Built web app to serve at `/` (production); omitted in development. */
  readonly webDist?: string;
  readonly allowedHostnames?: ReadonlySet<string>;
}

/** Cache file names are generated by us: sha256 + raster extension. */
const ARTWORK_FILE = /^[0-9a-f]{64}\.(jpg|png|gif|webp|tif)$/;

class NotFound extends Error {}

export function createApp(deps: AppDeps): express.Express {
  const { queries } = deps;
  const artwork = createArtworkRenderer(deps.artworkDir);
  const app = express();
  app.disable('x-powered-by');
  app.set('etag', 'strong');

  app.use(hostGuard(deps.allowedHostnames ?? LOOPBACK_HOSTNAMES));
  app.use(securityHeaders);
  app.use(readOnlyMethods);

  const api = express.Router();
  api.use(apiContentSecurityPolicy);

  api.get('/health', (_req, res) => {
    const body: Health = {
      status: 'ok',
      library: { configured: deps.libraryRoot !== null, available: isDirectory(deps.libraryRoot) },
      lastScan: queries.lastScan(),
    };
    res.json(body);
  });

  api.get('/health-report', (_req, res) => {
    res.json(deps.healthReport());
  });

  api.get('/stats', (_req, res) => {
    res.json(queries.stats());
  });

  api.get('/facets', (_req, res) => {
    res.json(queries.facets());
  });

  api.get('/albums', (req, res) => {
    res.json(queries.listAlbums(parse(albumListQuery, req.query)));
  });

  api.get('/albums/:id', (req, res) => {
    res.json(found(queries.getAlbum(parse(idParams, req.params).id)));
  });

  api.get('/tracks', (req, res) => {
    res.json(queries.listTracks(parse(trackListQuery, req.query)));
  });

  api.get('/artists', (req, res) => {
    res.json(queries.listArtists(parse(artistListQuery, req.query)));
  });

  api.get('/artists/:id', (req, res) => {
    res.json(found(queries.getArtist(parse(idParams, req.params).id)));
  });

  api.get('/search', (req, res) => {
    res.json(queries.search(parse(searchQuery, req.query).q));
  });

  api.get('/scans', (req, res) => {
    res.json(queries.listScans(parse(scanListQuery, req.query).limit));
  });

  api.get('/scans/:id', (req, res) => {
    res.json(found(queries.getScan(parse(idParams, req.params).id)));
  });

  api.get('/artwork/:id', async (req, res, next) => {
    const art = found(queries.getArtwork(parse(idParams, req.params).id));
    const { size } = parse(artworkQuery, req.query);
    // Defence in depth: the name comes from our own database, but it is still
    // checked before it gets anywhere near the filesystem.
    if (!ARTWORK_FILE.test(art.cacheFile)) throw new NotFound();
    let file: string;
    try {
      file = await artwork.render(art.cacheFile, size);
    } catch {
      // Missing from the cache, or not decodable: the UI shows a placeholder.
      throw new NotFound();
    }
    res.type('image/webp');
    // Content-addressed: the bytes behind an artwork URL never change.
    res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
    // Served relative to its directory: `send` refuses absolute paths that
    // pass through a dot-directory, and the cache lives under ~/.cache.
    res.sendFile(path.basename(file), { root: path.dirname(file) }, (error) => {
      if (error && !res.headersSent) next(new NotFound());
    });
  });

  api.use((_req, _res, next) => next(new NotFound()));
  app.use('/api', api);

  if (deps.webDist) {
    const webDist = deps.webDist;
    app.use(webContentSecurityPolicy);
    app.use(express.static(webDist, { index: false, dotfiles: 'deny', maxAge: '1h' }));
    // Client-side routes all render the app shell.
    app.get(/^\/(?!api\/).*/, (_req, res) => {
      res.sendFile('index.html', { root: webDist });
    });
  }

  app.use(errorHandler);
  return app;
}

function parse<T extends z.ZodType>(schema: T, input: unknown): z.infer<T> {
  return schema.parse(input);
}

function found<T>(value: T | null): T {
  if (value === null) throw new NotFound();
  return value;
}

function isDirectory(p: string | null): boolean {
  if (p === null) return false;
  try {
    return fs.statSync(p).isDirectory();
  } catch {
    return false;
  }
}

const errorHandler: ErrorRequestHandler = (error, _req: Request, res: Response, _next) => {
  let status = 500;
  let body: ApiError = { error: { code: 'INTERNAL', message: 'Internal error.' } };
  if (error instanceof ZodError) {
    status = 400;
    body = {
      error: {
        code: 'BAD_REQUEST',
        message: 'Invalid request.',
        issues: error.issues.map((i) => ({
          path: i.path.join('.') || '(query)',
          message: i.message,
        })),
      },
    };
  } else if (error instanceof NotFound) {
    status = 404;
    body = { error: { code: 'NOT_FOUND', message: 'Not found.' } };
  } else {
    // Details stay in the server log; the client gets a generic message.
    console.error(error);
  }
  if (res.headersSent) return;
  res.status(status).json(body);
};
